#!/usr/bin/env python3
"""Read-only PH12 physical inventory: literal names != source semantic parity.
Only use catalog JSON generated by disposable PostgreSQL 17 in GitHub CI.
"""
import argparse
import collections
import hashlib
import json
import os
import re
from pathlib import Path

ROOT=Path(__file__).resolve().parents[2]
INDEX="docs/analysis/PH01_148_ENTITY_FIELD_PHYSICAL_CANDIDATES.json"
SOURCE="docs/analysis/PH01_SOURCE_148_ENTITY_FIELD_INDEX.json"
SIMPLE=re.compile(r"^[a-z_][a-z0-9_]*[?]?$",re.I)
SAFE=re.compile(r"^[a-z_][a-z0-9_]*$",re.I)

def load(rel):
    return json.loads((ROOT/rel).read_text(encoding="utf8"))

def classify(old,catalog):
    """A candidate name hit is a search aid, NEVER an accepted mapping."""
    source=load(SOURCE)
    assert source["entity_count"]==len(source["entities"])==148,"SOURCE_ENTITIES_DRIFT"
    assert old["field_phrases"]==len(old["rows"])==786,"SOURCE_FIELDS_DRIFT"
    assert old["entities"]==148,"SOURCE_ENTITY_CENSUS_DRIFT"
    assert len({x["row_id"] for x in old["rows"]})==786,"DUPLICATE_FIELD_IDS"
    assert all(x.get("source_to_code_approved") is not True and
               x.get("actual_semantic_equivalence_certified") is not True
               for x in old["rows"]),"OLD_CANDIDATE_UNJUSTIFIED_APPROVAL"
    assert isinstance(catalog,list) and len(catalog)>150,"MISSING_CURRENT_PG_CATALOG"
    columns={}
    for x in catalog:
        assert {"table","column","type","nullable"}<=set(x),"CATALOG_ROW_INCOMPLETE"
        t=x["table"].lower()
        c=x["column"].lower()
        assert SAFE.fullmatch(t) and SAFE.fullmatch(c),"BAD_CATALOG_IDENTIFIER"
        assert (t,c) not in columns,"DUPLICATE_CATALOG_COLUMN"
        columns[t,c]=x
    tables={t for t,c in columns}
    assert {"user_accounts","tenants"}<=tables,"EXPECTED_CORE_TABLE_ABSENT"
    out=[]
    counts=collections.Counter()
    children=collections.defaultdict(collections.Counter)
    for x in old["rows"]:
        t=(x.get("sql_table_candidate") or "").lower().removeprefix("tto.")
        c=(x.get("sql_column_candidate") or "").lower()
        phrase=x["source_field_phrase"].lower().strip()
        literal=phrase.rstrip("?") if SIMPLE.fullmatch(phrase) else None
        proposed=c or literal or None
        # Match only the recorded table candidate. A field with a same-named
        # column in another table is *not* evidence of this source entity.
        if t in tables and proposed and (t,proposed) in columns:
            status="CANDIDATE_COLUMN_EXISTS_SEMANTICS_UNREVIEWED"
            detail=columns[t,proposed]
        elif t in tables:
            status="CANDIDATE_TABLE_EXISTS_FIELD_UNRESOLVED"
            detail=None
        else:
            status="CANDIDATE_TABLE_ABSENT_OR_UNMAPPED"
            detail=None
        counts[status]+=1
        children[x["child"]][status]+=1
        out.append({
            "sourceId":x["row_id"],"child":x["child"],
            "sourceEntity":x["source_entity"],
            "sourceField":x["source_field_phrase"],
            "historicalClass":x["classification"],
            "tableCandidate":t or None,
            "columnCandidate":proposed,
            "currentStatus":status,
            "observedType":detail["type"] if detail else None,
            "observedNullable":detail["nullable"] if detail else None,
            "semanticParityCertified":False,
            "review":"PENDING_AUTHORIZED_SOURCE_OWNER_AND_QA"
        })
    assert sum(counts.values())==786
    assert len({x["sourceId"] for x in out})==786
    return {"schemaVersion":"1.0",
     "classification":"PH12_CURRENT_PG17_LITERAL_AUDIT_NO_SEMANTIC_ACCEPTANCE",
     "sourceEntities":148,"sourceFieldPhrases":786,
     "oldAuditAsOf":old["date"],"oldAuditSqlTables":old["sql_tables"],
     "actualSchemaTableCount":len(tables),
     "actualSchemaColumnCount":len(columns),
     "migrationsAppliedFromExactHead":len(list((ROOT/"database/migrations").glob("[0-9][0-9][0-9][0-9]*.sql"))),
     "counts":dict(counts),
     "byChild":{child:dict(cnt) for child,cnt in sorted(children.items())},
     "semanticallyCertifiedFields":0,
     "formallyAcceptedEntities":0,
     "phase12":"HOLD",
     "observations":out}

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("--catalog",required=True)
    ap.add_argument("--output",required=True)
    args=ap.parse_args()
    assert os.getenv("CI")=="true" and not os.getenv("VERCEL"),"CI_PG17_ONLY"
    assert re.fullmatch("[a-f0-9]{40}",os.environ["GITHUB_SHA"])
    assert os.environ["GITHUB_RUN_ID"].isdigit()
    catalog=Path(args.catalog).resolve()
    target=Path(args.output).resolve()
    art=ROOT/"ph12-artifacts"
    assert catalog.parent==art and target.parent==art,"ARTIFACT_DIRECTORY_ONLY"
    report=classify(load(INDEX),json.loads(catalog.read_text(encoding="utf8")))
    report["provenance"]={
       "commitSha":os.environ["GITHUB_SHA"],
       "runId":os.environ["GITHUB_RUN_ID"],
       "sourceIndexSha256":hashlib.sha256((ROOT/SOURCE).read_bytes()).hexdigest(),
       "historicalCandidateSha256":hashlib.sha256((ROOT/INDEX).read_bytes()).hexdigest()}
    target.write_text(json.dumps(report,ensure_ascii=False,indent=2)+"\n",encoding="utf8")
    print("PH12_PHYSICAL_CURRENT_PG17_786_CLASSIFIED_NO_FORMAL_ACCEPTANCE_PASS")
    print(json.dumps({k:v for k,v in report.items() if k not in ("observations","byChild")},sort_keys=True))
if __name__=="__main__":
    main()
