CREATE TABLE tto.geo_provinces (
 province_code text PRIMARY KEY CHECK (province_code ~ '^[0-9]{2}$'),
 name text NOT NULL UNIQUE CHECK (length(btrim(name)) BETWEEN 2 AND 80),
 source_year text NOT NULL DEFAULT '1404' CHECK (source_year='1404')
);
CREATE TABLE tto.geo_counties (
 county_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 province_code text NOT NULL REFERENCES tto.geo_provinces(province_code),
 name text NOT NULL CHECK (length(btrim(name)) BETWEEN 2 AND 100 AND name=btrim(name)),
 official_county_code text CHECK (official_county_code IS NULL OR official_county_code ~ '^[0-9]{2}$'),
 provenance text NOT NULL CHECK (provenance IN ('REFERENCE_1404','NATIONAL_ADMIN_UNVERIFIED')),
 created_by uuid REFERENCES tto.user_accounts(user_id),
 created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 CONSTRAINT geo_county_source_integrity CHECK (
  (provenance='REFERENCE_1404' AND official_county_code IS NOT NULL AND created_by IS NULL)
  OR (provenance='NATIONAL_ADMIN_UNVERIFIED' AND official_county_code IS NULL AND created_by IS NOT NULL)
 ),
 UNIQUE(province_code,name),
 UNIQUE(province_code,official_county_code)
);
CREATE INDEX geo_counties_by_province ON tto.geo_counties(province_code,name);
ALTER TABLE tto.geo_provinces ENABLE ROW LEVEL SECURITY;
ALTER TABLE tto.geo_provinces FORCE ROW LEVEL SECURITY;
ALTER TABLE tto.geo_counties ENABLE ROW LEVEL SECURITY;
ALTER TABLE tto.geo_counties FORCE ROW LEVEL SECURITY;
REVOKE ALL ON tto.geo_provinces,tto.geo_counties FROM PUBLIC;
CREATE POLICY national_root_geo_provinces_read ON tto.geo_provinces FOR SELECT TO tto_app
 USING (tto.has_national_root());
CREATE POLICY national_root_geo_counties_read ON tto.geo_counties FOR SELECT TO tto_app
 USING (tto.has_national_root());
CREATE POLICY national_root_geo_counties_insert ON tto.geo_counties FOR INSERT TO tto_app
 WITH CHECK (tto.has_national_root() AND created_by=tto.context_actor_id()
  AND provenance='NATIONAL_ADMIN_UNVERIFIED' AND official_county_code IS NULL);
